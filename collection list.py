# Collection of List Operations

students = ["Rahul", "Arun", "Kiran", "Mohan"]

print(students)

# Adding an element
students.append("Ravi")
print(students)

# Inserting an element
students.insert(2, "Suresh")
print(students)

# Removing an element
students.remove("Arun")
print(students)

# Sorting the list
students.sort()
print(students)

# Reversing the list
students.reverse()
print(students)

# Finding length
print("\nNumber of students:", len(students))

# Clearing the list
students.clear()
print(students)